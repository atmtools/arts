struct PredefinedChannel {
  Numeric                        center{};
  std::vector<Numeric>           mixers;
  Numeric                        bandwidth{};
  PolarizationChoice             polarization{PolarizationChoice::I};
  std::optional<sensor::Channel> response;

  PredefinedChannel(Numeric              center,
                    std::vector<Numeric> mixers,
                    Numeric              bandwidth,
                    PolarizationChoice   polarization = PolarizationChoice::I)
      : center(center), mixers(std::move(mixers)), bandwidth(bandwidth), polarization(polarization) {}

  explicit PredefinedChannel(sensor::Channel response) : response(std::move(response)) {}
};

PredefinedChannel tabulated_channel(const String& name, AscendingGrid frequencies, Vector weights) {
  return PredefinedChannel{sensor::Channel{.channel = {.data_name  = name,
                                                       .data       = std::move(weights),
                                                       .grid_names = {String{"frequency"}},
                                                       .grids      = {std::move(frequencies)}}}};
}

